import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { initializeWorkspaceIdentity, resolveActiveParticipant } from '../workspace.js';
import { initializeNodeIdentity, exportPublicIdentity } from './identity.js';
import { pairPeer, exposeAgent } from './config.js';
import { addGrant } from './trust.js';
import { createCollaboration } from './collaboration.js';
import { enrollNetworkWake, monitorNetworkWake } from './wake.js';
import { collectNetworkDoctor } from './doctor.js';

test('exhausted Monitor reports budget, exits unsuccessfully and never replays or resets state', async t => {
  const root = await mkdtemp(join(tmpdir(), 'agentlink-monitor-budget-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const repo = join(root, 'repo'), state = join(root, 'state'), remote = join(root, 'remote'); await mkdir(repo);
  await initializeWorkspaceIdentity(repo); const actor = await resolveActiveParticipant(repo);
  await initializeNodeIdentity(state, 'local'); await initializeNodeIdentity(remote, 'remote');
  const identity = await exportPublicIdentity(remote);
  await pairPeer(state, { name: 'peer', address: 'https://127.0.0.1:1', identity, expectedFingerprint: identity.fingerprint });
  await exposeAgent(state, { agentId: actor.participantId, workspaceRoot: repo, peerName: 'peer' });
  const expiresAt = new Date(Date.now() + 60_000).toISOString();
  await addGrant(state, { grantId: 'grant', remoteNodeId: 'remote', remoteAgentId: 'frontend', localAgentId: actor.participantId, collaborationId: 'orders', actions: ['deliver'], expiresAt });
  await createCollaboration(state, { id: 'orders', localAgentId: actor.participantId, remoteNodeId: 'remote', remoteAgentId: 'frontend', topic: 'test', expiresAt });
  const c = await enrollNetworkWake({ id: 'budget', stateRoot: state, workspaceRoot: repo, peer: 'peer', remoteAgentId: 'frontend', authority: 'local', conversations: ['orders'], harness: 'claude-monitor', expiresAt, policy: 'Observe only', maxTurns: 1, mcpEntrypoint: fileURLToPath(new URL('../mcp/server.js', import.meta.url)) });
  const file = join(c.stateRoot, 'wake', 'budget-queue.json');
  const q = JSON.parse(await readFile(file, 'utf8')); q.turns = 1;
  await writeFile(file, JSON.stringify(q)); const before = await readFile(file, 'utf8');
  const child = spawnSync(process.execPath, [fileURLToPath(new URL('../cli.js', import.meta.url)), 'network', 'wake', 'monitor', '--state-root', state, '--id', c.id], { cwd: repo, encoding: 'utf8', timeout: 10_000 });
  assert.equal(child.error, undefined); assert.equal(child.status, 1);
  assert.match(child.stderr, /turn budget exhausted.*1\/1 turns used \(0 remaining\)/);
  assert.match(child.stderr, /owner authorization/);
  assert.deepEqual(JSON.parse(child.stdout), { status: 'budget-exhausted', enrollmentId: c.id, turns: 1, maxTurns: 1, remainingTurns: 0, reason: 'Turn budget exhausted; fresh enrollment requires owner authorization' });
  const report = await collectNetworkDoctor(state, repo);
  assert.equal(report.wake?.[0]?.remainingTurns, 0);
  assert(report.checks.some(c => c.code === 'wake:budget' && !c.ok && /Turn budget exhausted/.test(c.message)));
  assert.equal(await readFile(file, 'utf8'), before);
  q.stopped = true; await writeFile(file, JSON.stringify(q));
  const lines: string[] = []; await monitorNetworkWake(c.configPath, line => lines.push(line));
  assert.equal(JSON.parse(lines[0]!).status, 'stopped');
  await writeFile(c.configPath, JSON.stringify({ ...c, expiresAt: new Date(Date.now() - 1000).toISOString() }));
  const expiredChild = spawnSync(process.execPath, [fileURLToPath(new URL('../cli.js', import.meta.url)), 'network', 'wake', 'monitor', '--state-root', state, '--id', c.id], { cwd: repo, encoding: 'utf8', timeout: 10_000 });
  assert.equal(expiredChild.status, 1); assert.equal(JSON.parse(expiredChild.stdout).status, 'expired');
  assert.match(expiredChild.stderr, /expired.*without renewal/);
});
