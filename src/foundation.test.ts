test('association serializes a concurrent target registration across the bus switch', async (t) => {
  const source = await temporaryWorkspace(t, 'agentlink-association-race-source-');
  const target = await temporaryWorkspace(t, 'agentlink-association-race-target-');
  const sourceContext = await initializeWorkspaceIdentity(source);
  await initializeWorkspaceIdentity(target);

  let association!: Promise<unknown>;
  let registration!: Promise<Awaited<ReturnType<typeof registerParticipant>>>;
  let registrationSettled = false;
  await withFileLock(join(sourceContext.association.busPath, 'locks'), 'participants', async () => {
    association = associateWorkspace(source, target);
    const associationLockOwner = join(target, '.agentlink', 'locks', 'workspace-association.lock');
    const deadline = Date.now() + 2_000;
    while (true) {
      try {
        await readFile(associationLockOwner, 'utf8');
        break;
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT' || Date.now() >= deadline) throw error;
        await new Promise((resolve) => setTimeout(resolve, 10));
      }
    }
    registration = registerParticipant(target, { displayName: 'raced participant', select: false });
    void registration.then(
      () => { registrationSettled = true; },
      () => { registrationSettled = true; },
    );
    await new Promise((resolve) => setTimeout(resolve, 75));
    assert.equal(registrationSettled, false, 'registration must wait until the target association switch commits');
  }, { timeoutMs: 5_000 });

  await association;
  const registered = await registration;
  assert.equal(
    (await listParticipants(target)).some((participant) => participant.participantId === registered.participantId),
    true,
    'a successfully returned registration must remain visible on the associated bus',
  );
});

