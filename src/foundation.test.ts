test('a stale-lock reclaimer never mutates or claims a live published owner record', async (t) => {
  const cwd = await temporaryWorkspace(t, 'agentlink-live-lock-reclaim-barrier-');
  const locks = join(cwd, 'locks');
  const lock = join(locks, 'shared.lock');
  let signalAcquired!: () => void;
  let releaseOwner!: () => void;
  const acquired = new Promise<void>((resolve) => { signalAcquired = resolve; });
  const release = new Promise<void>((resolve) => { releaseOwner = resolve; });
  const holder = withFileLock(locks, 'shared', async () => {
    signalAcquired();
    await release;
  });
  await acquired;

  assert.equal((await lstat(lock)).isFile(), true, 'owner metadata must be completely published as the lock record');
  let observedReclaimClaim = false;
  let contenderDone = false;
  try {
    const contender = assert.rejects(
      withFileLock(locks, 'shared', async () => {}, { timeoutMs: 50, staleMs: -1, retryMs: 1 }),
      /Timed out acquiring lock shared/,
    ).finally(() => { contenderDone = true; });
    while (!contenderDone) {
      if ((await readdir(locks)).includes('shared.lock.reclaim')) observedReclaimClaim = true;
      await new Promise<void>((resolve) => setImmediate(resolve));
    }
    await contender;
  } finally {
    releaseOwner();
    await holder;
  }

  assert.equal(
    observedReclaimClaim,
    false,
    'a contender must not create a reclaim claim for a live owner',
  );
  assert.deepEqual(await readdir(locks), [], 'owner release must clean both lock and reclaim claim paths');
});

