test('owner revocation preserves audit records but removes participant eligibility and current quorum', async (t) => {
  const source = await temporaryWorkspace(t, 'agentlink-revoke-source-');
  const peer = await temporaryWorkspace(t, 'agentlink-revoke-peer-');
  await initializeWorkspaceIdentity(source);
  const conversation = await createConversation(source, { id: 'revoke', topic: 'Revocation', requiredApprovals: 2 });
  await writeConversationContract(source, { conversationId: conversation.id, topic: conversation.topic });
  await associateWorkspace(source, peer, { conversationId: conversation.id });
  const joined = await joinConversation(peer, conversation.id);
  const revision = (await readContractState(source, conversation.id)).revision!;
  await approveConversation(source, conversation.id, { revision });
  await approveConversation(peer, conversation.id, { revision });
  assert.equal(countRevisionApprovals(await readConversation(source, conversation.id), revision), 2);

  await revokeConversationParticipant(source, conversation.id, joined.participantId);
  const revoked = await readConversation(source, conversation.id);
  assert.equal(revoked.approvals.length, 2, 'historical approval audit remains append-only');
  assert.equal(revoked.participantIds.includes(joined.participantId), false);
  assert.equal(revoked.revokedParticipantIds.includes(joined.participantId), true);
  assert.equal(countRevisionApprovals(revoked, revision), 1);
  const summary = (await listConversations(source)).find((candidate) => candidate.id === conversation.id)!;
  assert.equal(summary.currentApprovalCount, 1);
  assert.equal(Object.hasOwn(summary, 'approvals'), false, 'listings expose current quorum, not raw historical approval arrays');
  await assert.rejects(joinConversation(peer, conversation.id), /revoked/i);
  await assert.rejects(approveConversation(peer, conversation.id, { revision }), /eligible|revoked/i);
  await assert.rejects(updateConversationContract(source, conversation.id, { status: 'Accepted' }), /1\/2 approvals/);
});

