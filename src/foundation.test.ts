test('bounded lock recovery removes an orphaned sibling reclaim claim', async (t) => {
  const cwd = await temporaryWorkspace(t, 'agentlink-orphan-reclaim-claim-');
  const locks = join(cwd, 'locks');
  const lock = join(locks, 'shared.lock');
  await mkdir(lock, { recursive: true });
  await writeFile(join(lock, 'owner.json'), `${JSON.stringify({
    pid: 2_147_483_647,
    token: 'dead-owner',
    acquiredAt: '2000-01-01T00:00:00.000Z',
  })}\n`, 'utf8');
  const old = new Date('2000-01-01T00:00:00.000Z');
  await utimes(lock, old, old);

  // A reclaimer can crash after exclusively creating this sibling and before
  // writing owner metadata or entering its cleanup path.
  await writeFile(`${lock}.reclaim`, '', 'utf8');
  const legacyClaim = `${lock}.reclaim`;
  const legacyDetails = await lstat(legacyClaim);
  const successorIdentity = createHash('sha256')
    .update(`legacy:${legacyDetails.dev}:${legacyDetails.ino}:${legacyDetails.birthtimeMs}`)
    .digest('hex')
    .slice(0, 32);
  const deadSuccessor = `${legacyClaim}.successor-${successorIdentity}`;
  await writeFile(deadSuccessor, `${JSON.stringify({
    pid: 2_147_483_647,
    token: 'dead-reclaim-successor',
  })}\n`, 'utf8');
  await utimes(legacyClaim, old, old);
  await utimes(deadSuccessor, old, old);

  let acquired = false;
  await withFileLock(locks, 'shared', async () => {
    acquired = true;
  }, { timeoutMs: 250, staleMs: 10, retryMs: 2 });
  assert.equal(acquired, true);
  assert.deepEqual(await readdir(locks), [], 'recovery must not leave a lock or reclaim claim behind');
});

